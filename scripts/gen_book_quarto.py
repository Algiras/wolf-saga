#!/usr/bin/env python3
"""Write books/N/_quarto.yml for the later books from the chapter files on disk, and the
print/store profiles for all six books.

    python3 scripts/gen_book_quarto.py 4 5        # _quarto.yml of books 4 and 5 (+ their profiles)
    python3 scripts/gen_book_quarto.py --profiles # _quarto-print.yml and _quarto-store.yml, books 1-6

Chapters are books/N/NN_slug.qmd; parts are chapters 1-10, 11-20 and 21-30.

The profiles (never put `chapters` in a profile: Quarto merges the lists) only select a format and an
output file:
    _quarto-print.yml  quarto render --profile print --to saga-print-pdf --no-clean   -> saga-N-print.pdf
    _quarto-store.yml  quarto render --profile store --to saga-store-epub --no-clean  -> saga-N-store.epub
The store profile also carries the e-book metadata from books/book_meta.yml (stable UUID, series,
description, ISBN once issued). See docs/PRINTING.md and docs/PUBLISHING.md.
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
BOOKS = {
    4: dict(sub="IV Knyga: Nematoma Karūna", parts=["Krikštas be Ugnies", "Nuo Jūros iki Jūros", "Nematoma Karūna"],
            desc="Epinis tamsiosios fantastikos pasakojimas apie Žemaitijos krikštą, Vytauto imperiją ir sulaikytą karūną (1411–1430)."),
    5: dict(sub="V Knyga: Vilko Palikimas", parts=["Tuštuma", "Brolis prieš Brolį", "Vaiduoklių Amžius"],
            desc="Epinis tamsiosios fantastikos pasakojimas apie Paskutinės Liepsnos užgesimą, pilietinį karą ir paskutinį vilką (1430–1450)."),
}
ROMAN = {1: "I", 2: "II", 3: "III", 4: "IV", 5: "V", 6: "VI"}
NAV = [("I knyga", "../"), ("II knyga", "../2/"), ("III knyga", "../3/"), ("IV knyga", "../4/"),
       ("V knyga", "../5/"), ("VI knyga (priešistorė)", "../6/"),
       ("Skaitymo tvarka", "../skaitymo_tvarka.html"), ("Wiki", "../wiki/")]

FORMAT = """format:
  html:
    theme:
      - cosmo
  pdf:
    documentclass: scrreprt
    number-sections: false
    sec-num-depth: 0
    toc: true
    pdf-engine: lualatex
    mainfont: "DejaVu Serif"
    monofont: "DejaVu Sans Mono"
    header-includes: |
      \\usepackage{{fontspec}}
      \\renewcommand{{\\partformat}}{{}}
      \\renewcommand{{\\chapterformat}}{{}}
  epub:
    cover-image: cover.jpg
    title: "Geležinio Vilko Saga {roman}: {title}"
    author: "Algimantas Krasauskas"
    description: "{desc}"
"""


def build(n):
    cfg, d = BOOKS[n], ROOT / "books" / str(n)
    chapters = sorted(p.name for p in d.glob("[0-3][0-9]_*.qmd"))
    nums = [int(c[:2]) for c in chapters]
    missing = sorted(set(range(1, 31)) - set(nums))
    dupes = sorted({x for x in nums if nums.count(x) > 1})
    if dupes:
        raise SystemExit(f"book {n}: duplicate chapter numbers {dupes}")
    out = ["project:", "  type: book", "", "lang: lt", "", "book:", '  title: "Geležinio Vilko Saga"',
           f'  subtitle: "{cfg["sub"]}"', '  author: "Algimantas Krasauskas"', f"  output-file: saga-{n}",
           '  date: "10/12/2026"', "  cover-image: cover.jpg", "  navbar:", "    right:"]
    for text, href in NAV:
        out += [f'      - text: "{text}"', f"        href: {'index.html' if href == f'../{n}/' else href}"]
    out += ["  chapters:", "    - index.qmd"]
    for i, part in enumerate(cfg["parts"]):
        out += [f'    - part: "{part}"', "      chapters:"]
        out += [f"        - {c}" for c in chapters if i * 10 < int(c[:2]) <= (i + 1) * 10]
    if (d / "istorine_pastaba.qmd").exists():
        out.append("    - istorine_pastaba.qmd")
    out += ["    - copyright.qmd", ""]
    title = cfg["sub"].split(": ", 1)[1]
    (d / "_quarto.yml").write_text("\n".join(out) + FORMAT.format(roman=ROMAN[n], title=title, desc=cfg["desc"]),
                                   encoding="utf-8")
    print(f"book {n}: {len(chapters)} chapters" + (f", MISSING {missing}" if missing else ""))


def _q(v):
    """YAML double-quoted scalar (JSON strings are valid YAML)."""
    return json.dumps(v, ensure_ascii=False)


def write_profiles(n):
    """books/N/_quarto-print.yml and _quarto-store.yml (book 1 lives in books/ itself)."""
    meta = yaml.safe_load((ROOT / "books" / "book_meta.yml").read_text(encoding="utf-8"))
    covers = yaml.safe_load((ROOT / "books" / "covers" / "covers.yml").read_text(encoding="utf-8"))
    b = next(x for x in meta["books"] if x["number"] == n)
    c = next(x for x in covers["books"] if x["number"] == n)
    ser = meta["series"]
    d = ROOT / "books" if n == 1 else ROOT / "books" / str(n)
    hook = "../scripts/polish_epub.py" if n == 1 else "../../scripts/polish_epub.py"

    (d / "_quarto-print.yml").write_text(
        "# Generated by scripts/gen_book_quarto.py. Print interior (KDP 6x9):\n"
        "#   quarto render --profile print --to saga-print-pdf --no-clean\n"
        "# Only a format and an output file: never add chapters here (Quarto merges the lists).\n"
        f"book:\n  output-file: saga-{n}-print\nformat:\n  saga-print-pdf: "
        + (f"\n    isbn: {_q(b['isbn_print'])}\n" if b.get("isbn_print") else "default\n"),
        encoding="utf-8")

    roman = ROMAN.get(n, "VI")
    lines = [
        "# Generated by scripts/gen_book_quarto.py from books/book_meta.yml. Store e-book (EPUB 3):",
        "#   quarto render --profile store --to saga-store-epub --no-clean",
        "# Only a format, an output file and metadata: never add chapters here.",
        "book:",
        f"  output-file: saga-{n}-store",
        f"  title: {_q(c['title_lt'])}",
        f"  subtitle: {_q(ser['name'] + ' \u00b7 ' + roman + ' knyga')}",
        "project:",
        "  post-render:",
        f"    - {hook}",
        "format:",
        "  saga-store-epub:",
        f"    identifier: {_q('urn:uuid:' + b['uuid'])}",
        f"    publisher: {_q(ser['publisher'])}",
        f"    rights: {_q(ser['rights'])}",
        f"    description: {_q(' '.join(b['blurb_lt'].split()))}",
        f"    belongs-to-collection: {_q(ser['name'])}",
        "    collection-type: series",
        f"    group-position: {n}",
        "",
    ]
    (d / "_quarto-store.yml").write_text("\n".join(lines), encoding="utf-8")
    print(f"book {n}: _quarto-print.yml, _quarto-store.yml")


if __name__ == "__main__":
    args = sys.argv[1:]
    if args == ["--profiles"]:
        for n in range(1, 7):
            write_profiles(n)
    else:
        for a in args or ["4", "5"]:
            build(int(a))
            write_profiles(int(a))
